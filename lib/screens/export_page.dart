import 'package:flutter/material.dart';
import 'package:tracker1/resource/colors/app_colors.dart';
import 'package:flutter/services.dart';
import '../models/expense.dart';

class ExportPage extends StatefulWidget {
  final List<TransactionItem> transactions;
  final String currencySymbol;

  const ExportPage({
    super.key,
    required this.transactions,
    required this.currencySymbol,
  });

  @override
  State<ExportPage> createState() => _ExportPageState();
}

class _ExportPageState extends State<ExportPage> {
  String _selectedFormat = 'CSV';
  String _selectedPeriod = 'All Time';
  bool _includeIncome = true;
  bool _includeExpenses = true;
  bool _showPreview = false;

  final List<String> _formats = ['CSV', 'Summary Text'];
  final List<String> _periods = ['All Time', 'This Month', 'Last Month', 'This Year'];

  List<TransactionItem> get _filteredTransactions {
    final now = DateTime.now();
    return widget.transactions.where((t) {
      if (!_includeIncome && t.isIncome) return false;
      if (!_includeExpenses && !t.isIncome) return false;
      switch (_selectedPeriod) {
        case 'This Month':
          return t.date.year == now.year && t.date.month == now.month;
        case 'Last Month':
          final lm = DateTime(now.year, now.month - 1);
          return t.date.year == lm.year && t.date.month == lm.month;
        case 'This Year':
          return t.date.year == now.year;
        default:
          return true;
      }
    }).toList();
  }

  String _buildCSV() {
    final sb = StringBuffer();
    sb.writeln('Date,Title,Category,Amount,Type');
    for (final t in _filteredTransactions) {
      final date = '${t.date.year}-${t.date.month.toString().padLeft(2, '0')}-${t.date.day.toString().padLeft(2, '0')}';
      final type = t.isIncome ? 'Income' : 'Expense';
      final amount = t.amount.toStringAsFixed(2);
      sb.writeln('$date,"${t.title}","${t.category}",$amount,$type');
    }
    return sb.toString();
  }

  String _buildSummaryText() {
    final sb = StringBuffer();
    final filtered = _filteredTransactions;
    double totalIncome = 0, totalExpense = 0;
    for (final t in filtered) {
      if (t.isIncome) { totalIncome += t.amount; }
      else { totalExpense += t.amount; }
    }
    sb.writeln('═══════════════════════════════');
    sb.writeln('  EXPENSE TRACKER REPORT');
    sb.writeln('  Period: $_selectedPeriod');
    sb.writeln('═══════════════════════════════');
    sb.writeln();
    sb.writeln('SUMMARY');
    sb.writeln('───────────────────────────────');
    sb.writeln('Total Transactions : ${filtered.length}');
    sb.writeln('Total Income       : ${widget.currencySymbol}${totalIncome.toStringAsFixed(2)}');
    sb.writeln('Total Expenses     : ${widget.currencySymbol}${totalExpense.toStringAsFixed(2)}');
    sb.writeln('Net Balance        : ${widget.currencySymbol}${(totalIncome - totalExpense).toStringAsFixed(2)}');
    sb.writeln();
    sb.writeln('TRANSACTIONS');
    sb.writeln('───────────────────────────────');
    for (final t in filtered) {
      final date = '${t.date.month}/${t.date.day}/${t.date.year}';
      final sign = t.isIncome ? '+' : '-';
      sb.writeln('$date | ${t.title.padRight(20)} | $sign${widget.currencySymbol}${t.amount.toStringAsFixed(2)}');
    }
    sb.writeln();
    sb.writeln('Generated by Expense Tracker App');
    return sb.toString();
  }

  String get _exportContent => _selectedFormat == 'CSV' ? _buildCSV() : _buildSummaryText();

  void _copyToClipboard() {
    Clipboard.setData(ClipboardData(text: _exportContent));
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text('$_selectedFormat data copied to clipboard!'),
        behavior: SnackBarBehavior.floating,
        backgroundColor: AppColors.incomeDark,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final filtered = _filteredTransactions;
    double totalIncome = 0, totalExpense = 0;
    for (final t in filtered) {
      if (t.isIncome) { totalIncome += t.amount; }
      else { totalExpense += t.amount; }
    }

    return SingleChildScrollView(
      padding: const EdgeInsets.fromLTRB(16, 16, 16, 100),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          // Export Options Card
          Card(
            shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
            elevation: 2,
            child: Padding(
              padding: const EdgeInsets.all(16),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  const Text('Export Options', style: TextStyle(fontSize: 16, fontWeight: FontWeight.bold)),
                  const SizedBox(height: 16),

                  // Format Selector
                  const Text('Format', style: TextStyle(fontSize: 13, fontWeight: FontWeight.w500)),
                  const SizedBox(height: 8),
                  Row(
                    children: _formats.map((f) {
                      final selected = f == _selectedFormat;
                      return Expanded(
                        child: GestureDetector(
                          onTap: () => setState(() => _selectedFormat = f),
                          child: Container(
                            margin: const EdgeInsets.only(right: 8),
                            padding: const EdgeInsets.symmetric(vertical: 10),
                            decoration: BoxDecoration(
                              color: selected ? theme.colorScheme.primary : theme.colorScheme.primary.withValues(alpha: 0.08),
                              borderRadius: BorderRadius.circular(10),
                              border: Border.all(
                                color: selected ? theme.colorScheme.primary : theme.colorScheme.primary.withValues(alpha: 0.3),
                              ),
                            ),
                            child: Center(
                              child: Text(
                                f,
                                style: TextStyle(
                                  color: selected ? AppColors.white : theme.colorScheme.primary,
                                  fontWeight: FontWeight.w600,
                                  fontSize: 13,
                                ),
                              ),
                            ),
                          ),
                        ),
                      );
                    }).toList(),
                  ),
                  const SizedBox(height: 16),

                  // Period Selector
                  const Text('Period', style: TextStyle(fontSize: 13, fontWeight: FontWeight.w500)),
                  const SizedBox(height: 8),
                  DropdownButtonFormField<String>(
                    initialValue: _selectedPeriod,
                    decoration: const InputDecoration(
                      border: OutlineInputBorder(),
                      contentPadding: EdgeInsets.symmetric(horizontal: 12, vertical: 10),
                      isDense: true,
                    ),
                    items: _periods.map((p) => DropdownMenuItem(value: p, child: Text(p))).toList(),
                    onChanged: (v) => setState(() => _selectedPeriod = v!),
                  ),
                  const SizedBox(height: 16),

                  // Include Filters
                  const Text('Include', style: TextStyle(fontSize: 13, fontWeight: FontWeight.w500)),
                  const SizedBox(height: 4),
                  Row(
                    children: [
                      Expanded(
                        child: CheckboxListTile(
                          dense: true,
                          title: const Text('Income', style: TextStyle(fontSize: 13)),
                          value: _includeIncome,
                          onChanged: (v) => setState(() => _includeIncome = v!),
                          contentPadding: EdgeInsets.zero,
                          controlAffinity: ListTileControlAffinity.leading,
                        ),
                      ),
                      Expanded(
                        child: CheckboxListTile(
                          dense: true,
                          title: const Text('Expenses', style: TextStyle(fontSize: 13)),
                          value: _includeExpenses,
                          onChanged: (v) => setState(() => _includeExpenses = v!),
                          contentPadding: EdgeInsets.zero,
                          controlAffinity: ListTileControlAffinity.leading,
                        ),
                      ),
                    ],
                  ),
                ],
              ),
            ),
          ),
          const SizedBox(height: 16),

          // Quick Stats
          Card(
            shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
            elevation: 2,
            child: Padding(
              padding: const EdgeInsets.all(16),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  const Text('Export Summary', style: TextStyle(fontSize: 15, fontWeight: FontWeight.bold)),
                  const SizedBox(height: 12),
                  Row(
                    mainAxisAlignment: MainAxisAlignment.spaceAround,
                    children: [
                      _quickStat('Rows', '${filtered.length}', Icons.table_rows, AppColors.info),
                      _quickStat('Income', '${widget.currencySymbol}${totalIncome.toStringAsFixed(0)}', Icons.arrow_downward, AppColors.income),
                      _quickStat('Expenses', '${widget.currencySymbol}${totalExpense.toStringAsFixed(0)}', Icons.arrow_upward, AppColors.expense),
                    ],
                  ),
                ],
              ),
            ),
          ),
          const SizedBox(height: 16),

          // Action Buttons
          Row(
            children: [
              Expanded(
                child: OutlinedButton.icon(
                  onPressed: () => setState(() => _showPreview = !_showPreview),
                  icon: Icon(_showPreview ? Icons.visibility_off : Icons.visibility),
                  label: Text(_showPreview ? 'Hide Preview' : 'Preview'),
                  style: OutlinedButton.styleFrom(
                    padding: const EdgeInsets.symmetric(vertical: 14),
                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
                  ),
                ),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: ElevatedButton.icon(
                  onPressed: filtered.isEmpty ? null : _copyToClipboard,
                  icon: const Icon(Icons.copy),
                  label: const Text('Copy to Clipboard'),
                  style: ElevatedButton.styleFrom(
                    padding: const EdgeInsets.symmetric(vertical: 14),
                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
                  ),
                ),
              ),
            ],
          ),

          if (filtered.isEmpty) ...[
            const SizedBox(height: 12),
            Container(
              padding: const EdgeInsets.all(12),
              decoration: BoxDecoration(
                color: AppColors.warning.withValues(alpha: 0.1),
                borderRadius: BorderRadius.circular(12),
                border: Border.all(color: AppColors.warning.withValues(alpha: 0.3)),
              ),
              child: const Row(
                children: [
                  Icon(Icons.info_outline, color: AppColors.warning, size: 18),
                  SizedBox(width: 8),
                  Text('No transactions match selected filters', style: TextStyle(fontSize: 13, color: AppColors.warning)),
                ],
              ),
            ),
          ],

          // Preview Panel
          if (_showPreview && filtered.isNotEmpty) ...[
            const SizedBox(height: 16),
            const Text('Preview', style: TextStyle(fontSize: 15, fontWeight: FontWeight.bold)),
            const SizedBox(height: 8),
            Container(
              width: double.infinity,
              padding: const EdgeInsets.all(12),
              decoration: BoxDecoration(
                color: AppColors.gray100,
                borderRadius: BorderRadius.circular(12),
                border: Border.all(color: AppColors.gray300),
              ),
              child: Text(
                _exportContent.substring(0, _exportContent.length.clamp(0, 1500)) +
                    (_exportContent.length > 1500 ? '\n...[truncated for preview]' : ''),
                style: const TextStyle(fontSize: 11, fontFamily: 'monospace', color: AppColors.black87),
              ),
            ),
          ],
        ],
      ),
    );
  }

  Widget _quickStat(String label, String value, IconData icon, Color color) {
    return Column(
      children: [
        Icon(icon, color: color, size: 22),
        const SizedBox(height: 4),
        Text(value, style: TextStyle(fontWeight: FontWeight.bold, color: color, fontSize: 14)),
        Text(label, style: TextStyle(fontSize: 11, color: AppColors.gray500)),
      ],
    );
  }
}
